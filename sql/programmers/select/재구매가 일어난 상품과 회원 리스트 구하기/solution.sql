-- 재구매가 일어난 상품과 회원 리스트 구하기 (Lv2)
-- 결과: 손도 못 댐. 해설을 보고 이해했다. 나중에 아무것도 안 보고 다시 풀 문제.

-- 정답 (해설을 보고 적었다. 내가 직접 떠올린 풀이가 아니다)
SELECT USER_ID, PRODUCT_ID
FROM ONLINE_SALE
GROUP BY USER_ID, PRODUCT_ID
HAVING COUNT(*) > 1
ORDER BY USER_ID ASC, PRODUCT_ID DESC;

-- 메모
-- 막힌 지점: 문제를 쿼리로 바꾸는 첫 걸음이 안 떠올랐다. "재구매"를 어떻게 세는지 몰랐다.
--
-- 1) "재구매"를 데이터의 말로 바꾸기
--    문제에 "동일한 날짜, 회원 ID, 상품 ID 조합에 대해서는 하나의 판매 데이터만 존재합니다"가 있다.
--    그러니까 (회원, 상품)이 같은 행이 2개 이상이면 날짜가 서로 다르다는 뜻이고,
--    그게 바로 다른 날 또 샀다 = 재구매다.
--    -> 재구매 = 같은 (USER_ID, PRODUCT_ID) 조합의 행 수가 2 이상
--    문제 설명에 이런 "하나만 존재한다" 같은 문장이 있으면 세는 기준을 알려주는 힌트다.
--
-- 2) 조합 단위로 묶기
--    GROUP BY USER_ID, PRODUCT_ID
--    GROUP BY에 열을 두 개 적으면 두 값의 "쌍"이 같은 행끼리 한 줄이 된다.
--    (1, 100)과 (1, 200)은 다른 그룹이다.
--
-- 3) 2번 이상인 그룹만 남기기 -> HAVING COUNT(*) > 1
--    여기서 WHERE를 쓰면 에러다. 이게 이 문제의 핵심이다.
--      WHERE  : 묶기 전에 행을 거른다. 원본 열만 쓸 수 있다.
--      HAVING : 묶은 뒤에 그룹을 거른다. COUNT, SUM 같은 집계값을 쓸 수 있다.
--    COUNT(*)는 묶은 다음에야 생기는 값이라 WHERE COUNT(*) > 1은 쓸 수 없다.
--    COUNT(*) >= 2 라고 써도 같다.
--
-- 4) 정렬 방향이 서로 다르다. 회원 ID 오름차순, 상품 ID 내림차순.
--    ORDER BY USER_ID ASC, PRODUCT_ID DESC
--
-- 기억해 둘 점:
--   "중복", "두 번 이상", "재구매", "여러 개" 같은 말이 나오면
--   GROUP BY로 묶고 HAVING COUNT로 거르는 모양을 먼저 떠올린다.
--     SELECT 묶는 기준 FROM 테이블 GROUP BY 묶는 기준 HAVING COUNT(*) > 1
--   이건 "동명 동물 수 찾기", "중복 제거하기" 같은 문제에서도 그대로 쓰인다.
--   무엇을 세야 하는지 모르겠으면, 결과로 뽑아야 하는 열이 곧 묶는 기준이다.
--   여기서는 출력이 USER_ID, PRODUCT_ID이고 GROUP BY도 그 두 열이다.
