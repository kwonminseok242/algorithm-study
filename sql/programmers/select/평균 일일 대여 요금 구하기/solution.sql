-- 내 풀이 (수정)
SELECT ROUND(AVG(DAILY_FEE), 0) AS AVERAGE_FEE
FROM CAR_RENTAL_COMPANY_CAR
WHERE CAR_TYPE = 'SUV';

-- 메모
-- 틀린 이유:
--   1) 반올림하는 법을 몰랐다. (ROUND 함수를 아예 쓸 생각을 못 했다)
--      ROUND(값, 자리수) — 자리수는 "남길 소수 자리의 개수"다.
--        ROUND(1234.5678)     -> 1235     (자리수를 적지 않으면 0과 같다)
--        ROUND(1234.5678, 0)  -> 1235
--        ROUND(1234.5678, 1)  -> 1234.6
--        ROUND(1234.5678, 2)  -> 1234.57
--      문제 문구를 자리수로 옮기는 법: "소수 첫 번째 자리에서 반올림"은
--      그 자리를 반올림해 없앤다는 뜻이라 0, "소수 둘째 자리까지"는 남긴다는 뜻이라 2.
--      "에서"면 그 자리가 사라지고, "까지"면 그 자리가 남는다.
--      버림은 TRUNCATE(값, 자리수), 내림은 FLOOR(값), 올림은 CEIL(값).
--      -> 자세한 표는 sql/SQL_문법.md의 "5. 집계 함수 > 반올림과 자리수"
--   2) 컬럼명을 지정하지 않았다. 문제가 컬럼명을 정해주면 AS로 별칭을 붙여야 한다.
--      별칭이 없으면 헤더가 AVG(DAILY_FEE)로 나와서 채점에서 틀린다.
-- 접근 방법:
--   조건은 WHERE CAR_TYPE = 'SUV'로 먼저 걸러내고, 남은 행 전체를 AVG로 접는다.
--   GROUP BY가 없으면 테이블 전체가 한 그룹이라 결과는 한 행이다.
--   마지막에 문제가 요구한 반올림(ROUND)과 컬럼명(AS)을 입히고 제출한다.
-- 체크리스트: 문제에 "반올림", "컬럼명", "정렬" 문구가 있으면 쿼리에 그대로 옮겼는지 확인한다.
