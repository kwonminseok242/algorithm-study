-- 모든 레코드 조회하기 (Lv1)
-- 결과: 통과 (한 번에 맞춤)

-- 내 풀이
SELECT *
FROM ANIMAL_INS
ORDER BY ANIMAL_ID ASC;

-- 메모
-- 틀린 이유: 없음.
-- 접근 방법:
--   "모든 동물의 정보" -> 열을 다 보여주라는 뜻이니 SELECT *
--   "ANIMAL_ID순으로" -> ORDER BY ANIMAL_ID  (순서 말이 없으면 오름차순)
-- 기억해 둘 점:
--   SELECT *는 문제가 "모든 정보"를 달라고 할 때만 쓴다.
--   출력할 열을 하나하나 지정한 문제에서 *를 쓰면 열이 더 나와서 틀린다.
--   ANIMAL_ID는 VARCHAR이라 문자 순서로 정렬된다. 숫자처럼 보여도 'A10'이 'A9'보다 앞이다.
--   이 문제는 채점 기준이 ANIMAL_ID 순서라서 그대로 두면 된다.
